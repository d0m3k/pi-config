#!/bin/bash
set -e

AGENT_DIR="$HOME/.pi/agent"
EXT_DIR="$AGENT_DIR/extensions"
CONFIG_DIR="$(cd "$(dirname "$0")" && pwd)"

echo "=== pi-config setup ==="
echo ""

# 1. Ensure agent directories exist
mkdir -p "$AGENT_DIR" "$EXT_DIR"

# 2. Copy extensions
echo "[1/4] Installing extensions..."
for ext in pi-go-bars-local pi-statusline-local; do
  if [ -d "$CONFIG_DIR/extensions/$ext" ]; then
    rm -rf "$EXT_DIR/$ext"
    cp -r "$CONFIG_DIR/extensions/$ext" "$EXT_DIR/$ext"
    echo "  ✓ $ext"
  else
    echo "  ✗ $ext not found — skipping"
  fi
done

# 3. Install settings.json (merge new extensions, keep existing)
echo "[2/4] Installing settings..."
SETTINGS_FILE="$AGENT_DIR/settings.json"
REPO_SETTINGS="$CONFIG_DIR/settings.json"

if [ -f "$SETTINGS_FILE" ]; then
  # Merge: keep existing settings, update only the packages list.
  # Uses Node (always available with pi) — this repo targets Termux,
  # where python3 is NOT installed; the old python path would fail and
  # silently clobber the user's settings.json with the repo defaults.
  if SETTINGS_FILE="$SETTINGS_FILE" REPO_SETTINGS="$REPO_SETTINGS" node -e '
    const fs = require("fs");
    const current = JSON.parse(fs.readFileSync(process.env.SETTINGS_FILE, "utf8"));
    const repo = JSON.parse(fs.readFileSync(process.env.REPO_SETTINGS, "utf8"));
    current.packages = repo.packages ?? current.packages ?? [];
    fs.writeFileSync(process.env.SETTINGS_FILE, JSON.stringify(current, null, 2) + "\n");
    console.log("  ✓ settings.json updated");
  '; then
    :
  else
    echo "  ⚠ could not merge settings.json — leaving existing file untouched"
  fi
else
  cp "$REPO_SETTINGS" "$SETTINGS_FILE"
  echo "  ✓ settings.json created"
fi

# 4. Assemble the shared context file
#
# pi loads <agent-dir>/AGENTS.md in every session, in every working directory, so
# that path is the one place both hosts read. It is generated: common facts from
# AGENTS.md, then the platform profile, then versions probed at install time,
# then the optional private overlay. pi has no include directive for context
# files, hence the concatenation.
echo "[3/4] Assembling AGENTS.md..."
AGENT_MD="$AGENT_DIR/AGENTS.md"
HOST_PROFILE=""
if [ -n "$TERMUX_VERSION" ]; then
  HOST_PROFILE=termux-android
elif [ "$(uname -s)" = Linux ] && [ "$(uname -m)" = x86_64 ]; then
  # x86_64 Linux is not necessarily the laptop — require Fedora to claim it.
  if grep -qs '^ID=fedora' /etc/os-release; then
    HOST_PROFILE=fedora-intel
  fi
fi

# Probed facts. Never committed: versions drift with every `pi update`, and a
# stale number in a context file is worse than no number.
PI_VER="$(cat "$AGENT_DIR/install/current-version" 2>/dev/null || true)"
[ -n "$PI_VER" ] || PI_VER="$(pi --version 2>/dev/null | head -n 1 || true)"
OMP_VER="$(omp --version 2>/dev/null | head -n 1 || true)"
NODE_VER="$(node -v 2>/dev/null || true)"
PI_DOCS=""
if [ -n "$PI_VER" ] && [ -d "$AGENT_DIR/install/releases/$PI_VER/node_modules/@earendil-works/pi-coding-agent" ]; then
  PI_DOCS="$AGENT_DIR/install/releases/$PI_VER/node_modules/@earendil-works/pi-coding-agent"
fi

{
  printf '<!-- Generated by pi-config/setup.sh — edit ~/pi-config, then re-run; do not edit this copy. -->\n\n'
  cat "$CONFIG_DIR/AGENTS.md"
  printf '\n---\n\n'
  if [ -n "$HOST_PROFILE" ] && [ -f "$CONFIG_DIR/hosts/$HOST_PROFILE.md" ]; then
    cat "$CONFIG_DIR/hosts/$HOST_PROFILE.md"
  else
    printf '## Host profile\n\nNo profile matched this platform (%s %s). Add `hosts/<name>.md` to pi-config and re-run `./setup.sh`.\n' "$(uname -s)" "$(uname -m)"
  fi
  printf '\n---\n\n## Runtime facts (generated)\n\n'
  printf 'Probed by `./setup.sh` on %s — re-run it after `pi update`, `omp` upgrades or `git pull`.\n\n' "$(date -u '+%Y-%m-%d %H:%M UTC')"
  printf '| Fact | Value |\n|---|---|\n'
  printf '| pi | %s (managed install) |\n' "${PI_VER:-unknown}"
  printf '| omp | %s |\n' "${OMP_VER:-not installed}"
  printf '| node | %s |\n' "${NODE_VER:-not on PATH}"
  printf '| pi docs / examples | %s |\n' "${PI_DOCS:-not found}"
  printf '| platform | %s %s |\n' "$(uname -s)" "$(uname -m)"
  printf '| host profile | %s |\n' "${HOST_PROFILE:-none matched}"
  if [ -f "$CONFIG_DIR/hosts/private.local.md" ]; then
    printf '\n---\n\n'
    cat "$CONFIG_DIR/hosts/private.local.md"
  fi
} > "$AGENT_MD"
echo "  ✓ ~/.pi/agent/AGENTS.md (common + ${HOST_PROFILE:-no host profile} + runtime facts$( [ -f "$CONFIG_DIR/hosts/private.local.md" ] && printf ' + private'))"

if [ -f "$HOME/AGENTS.md" ]; then
  echo "  ⚠ $HOME/AGENTS.md is unmanaged and loads too, for sessions under \$HOME"
  echo "    → duplicate/stale instructions; remove it: rm $HOME/AGENTS.md"
fi

# 5. pi-go-bars credentials
echo "[4/4] Go bars credentials..."
GOBARS_CONFIG="$AGENT_DIR/pi-go-bars.json"
if [ ! -f "$GOBARS_CONFIG" ]; then
  echo ""
  echo "  pi-go-bars needs Opencode Go credentials."
  echo "  You can skip this and run /gobars-setup inside pi later."
  echo ""
  read -p "  Enter workspace ID (or press Enter to skip): " WORKSPACE_ID
  if [ -n "$WORKSPACE_ID" ]; then
    read -p "  Enter auth cookie (auth, starts Fe26.2**): " AUTH_COOKIE
    read -p "  Enter session cookie (__Host-console_session, starts st_): " SESSION_COOKIE
    mkdir -p "$AGENT_DIR"
    cat > "$GOBARS_CONFIG" << JSONEOF
{
  "workspaceId": "$WORKSPACE_ID",
  "authCookie": "$AUTH_COOKIE",
  "sessionCookie": "$SESSION_COOKIE"
}
JSONEOF
    chmod 600 "$GOBARS_CONFIG"
    echo "  ✓ pi-go-bars.json created"
  else
    echo "  ⏭ skipped"
  fi
else
  HAVE_SESSION="$(
    GOBARS_CONFIG="$GOBARS_CONFIG" node -e '
      const fs = require("fs");
      try {
        const c = JSON.parse(fs.readFileSync(process.env.GOBARS_CONFIG, "utf8"));
        process.stdout.write(typeof c.sessionCookie === "string" && c.sessionCookie ? "1" : "");
      } catch {}
    '
  )"
  if [ -n "$HAVE_SESSION" ]; then
    echo "  ✓ already exists with sessionCookie, leaving unchanged"
  else
    echo ""
    echo "  ⚠ existing pi-go-bars.json has no 'sessionCookie' — required since"
    echo "    opencode.ai switched to the console JSON API (auth alone gives 401)."
    read -p "  Enter __Host-console_session cookie (or press Enter to skip): " SESSION_COOKIE
    if [ -n "$SESSION_COOKIE" ]; then
      GOBARS_CONFIG="$GOBARS_CONFIG" SESSION_COOKIE="$SESSION_COOKIE" node -e '
        const fs = require("fs");
        const c = JSON.parse(fs.readFileSync(process.env.GOBARS_CONFIG, "utf8"));
        c.sessionCookie = process.env.SESSION_COOKIE;
        fs.writeFileSync(process.env.GOBARS_CONFIG, JSON.stringify(c, null, 2) + "\n");
      '
      echo "  ✓ sessionCookie added"
    else
      echo "  ⏭ skipped — statusline will show a 'missing session cookie' hint"
    fi
  fi
fi

echo ""
echo "=== Done! Restart pi ==="
